package com.gitlab.mbarberot.kriollo.services.templating

import com.github.jknack.handlebars.Handlebars
import com.github.jknack.handlebars.Template
import com.github.jknack.handlebars.TypeSafeTemplate
import com.github.jknack.handlebars.io.ClassPathTemplateLoader
import com.gitlab.mbarberot.kriollo.generator.git.GitIgnoreModel
import com.gitlab.mbarberot.kriollo.generator.git.GitIgnoreRules
import gg.jte.ContentType
import gg.jte.TemplateEngine
import gg.jte.output.StringOutput
import gg.jte.resolve.DirectoryCodeResolver
import org.assertj.core.api.Assertions
import org.junit.jupiter.api.Test
import kotlin.io.path.Path
import kotlin.reflect.KClass

class TemplateEngineTests {

    @Test
    fun jteTest() {
        // Arrange
        val templateEngine = TemplateEngine.create(
            DirectoryCodeResolver(Path("src/main/jte")),
            ContentType.Plain
        ).apply { setTrimControlStructures(true) }

        // Act
        val out = StringOutput()
        templateEngine.render("genertor/git/gitignore.kte", model(), out)
        val result = out.toString()

        // Assert
        Assertions.assertThat(result).isEqualTo(expectedGitIgnoreOutput())
    }

    @Test
    fun handlebarsTest() {
        // Arrange
        val loader = ClassPathTemplateLoader().apply { prefix = "/templates" }
        val templateEngine = Handlebars(loader).apply { prettyPrint(true) }
        val typeSafeTemplate: GitIgnoreTemplate = templateEngine.typeSafeCompile("generator/git/gitignore", GitIgnoreTemplate::class)

        // Act
        val result = typeSafeTemplate.apply(model())

        // Assert
        Assertions.assertThat(result).isEqualTo(expectedGitIgnoreOutput())
    }

    private fun expectedGitIgnoreOutput(): String = """
        # /!\ Warning
        # This file is generated by Kriollo, do not edit it manually 
        
        # Java rules
        *.jar
        *.class
        target/
        
        """.trimIndent()

    private fun model(): GitIgnoreModel {
        val javaRules = GitIgnoreRules(
            description = "Java rules", rules = listOf(
                "*.jar",
                "*.class",
                "target/"
            )
        )
        val model = GitIgnoreModel(blocks = listOf(javaRules))
        return model
    }
}

fun <S, T : TypeSafeTemplate<S>> Handlebars.typeSafeCompile(templatePath: String, klass: KClass<T>): T {
    return compile(templatePath).`as`(klass.java)
}

interface GitIgnoreTemplate : TypeSafeTemplate<GitIgnoreModel>